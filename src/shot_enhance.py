"""Sharper design shots (polish round, step 2): structure-preserving detail enhancement of the perspective shots
only (the panorama is not touched).

    esrgan_shot   Real-ESRGAN x2 on the 1024 x 768 shot, resized (area) to the output width
    tile_upscale  SD 1.5 + ControlNet tile (lllyasviel/control_v11f1e_sd15_tile, checkpoints/controlnet_tile):
                  the shot is resized (Lanczos) to the output size, cut into overlapping 768 px tiles, each tile is
                  re-generated by img2img (strength s, the same prompt, a fixed seed) with the tile itself as the
                  ControlNet condition (the tile model keeps local structure and colours), and the tiles are blended
                  back with feathered (cos) weights
"""

from __future__ import annotations

import time
from pathlib import Path

import cv2
import numpy as np
import torch

ROOT = Path(__file__).resolve().parents[1]
CONTROLNET_TILE = ROOT / "checkpoints" / "controlnet_tile"
OUT_W, OUT_H = 1536, 1152
TILE, OVERLAP = 768, 128
STEPS, GUIDANCE = 30, 5.0
SUFFIX = ", interior design photo, sharp focus, highly detailed, realistic materials"
NEGATIVE = "blurry, lowres, soft, distorted, deformed, text, watermark, people"


def load_tile_pipeline(device, lora_dir=None):
    from diffusers import ControlNetModel, DDIMScheduler, StableDiffusionControlNetImg2ImgPipeline
    from .generate_2d import BASE_MODEL
    cn = ControlNetModel.from_pretrained(str(CONTROLNET_TILE), dtype=torch.float16)
    pipe = StableDiffusionControlNetImg2ImgPipeline.from_pretrained(BASE_MODEL, controlnet=cn, dtype=torch.float16,
                                                                    variant="fp16", safety_checker=None,
                                                                    requires_safety_checker=False)
    pipe.scheduler = DDIMScheduler.from_config(pipe.scheduler.config)
    if lora_dir is not None:
        pipe.load_lora_weights(str(lora_dir))
        pipe.fuse_lora()
        pipe.unload_lora_weights()
    pipe.set_progress_bar_config(disable=True)
    return pipe.to(device)


def _starts(n: int, tile: int, overlap: int) -> list[int]:
    if n <= tile:
        return [0]
    step = tile - overlap
    s = list(range(0, n - tile, step)) + [n - tile]
    return sorted(set(s))


@torch.inference_mode()
def tile_upscale(pipe, img: np.ndarray, prompt: str, strength: float = 0.4, seed: int = 0, out_w: int = OUT_W,
                 out_h: int = OUT_H, cond_scale: float = 1.0) -> tuple[np.ndarray, float]:
    from PIL import Image
    t0 = time.perf_counter()
    up = cv2.resize(img, (out_w, out_h), interpolation=cv2.INTER_LANCZOS4)
    acc = np.zeros((out_h, out_w, 3), np.float64)
    wsum = np.zeros((out_h, out_w, 1), np.float64)
    win = np.outer(np.hanning(TILE + 2)[1:-1], np.hanning(TILE + 2)[1:-1])[..., None] + 1e-3
    k = 0
    for y in _starts(out_h, TILE, OVERLAP):
        for x in _starts(out_w, TILE, OVERLAP):
            t = up[y:y + TILE, x:x + TILE]
            gen = torch.Generator(pipe.device).manual_seed(int(seed) + k)
            out = pipe(prompt=prompt + SUFFIX, negative_prompt=NEGATIVE, image=Image.fromarray(t),
                       control_image=Image.fromarray(t), strength=float(strength), num_inference_steps=STEPS,
                       guidance_scale=GUIDANCE, controlnet_conditioning_scale=cond_scale, generator=gen,
                       height=t.shape[0], width=t.shape[1]).images[0]
            o = np.asarray(out.convert("RGB")).astype(np.float64)
            w = win[:t.shape[0], :t.shape[1]]
            acc[y:y + TILE, x:x + TILE] += o * w
            wsum[y:y + TILE, x:x + TILE] += w
            k += 1
    res = np.clip(acc / np.maximum(wsum, 1e-9), 0, 255).astype(np.uint8)
    return res, time.perf_counter() - t0


@torch.inference_mode()
def esrgan_shot(net, img: np.ndarray, out_w: int = OUT_W, out_h: int = OUT_H) -> tuple[np.ndarray, float]:
    from .generate_pano import esrgan_upscale
    t0 = time.perf_counter()
    up = esrgan_upscale(net, img, tile=512, overlap=16, wrap_pad=0)
    return cv2.resize(up, (out_w, out_h), interpolation=cv2.INTER_AREA), time.perf_counter() - t0
